import { Duration, Predicate, Schema } from 'effect';
import { HttpServerResponse } from 'effect/http';
import type { Client } from 'oauth2-server';
import {
  consentCookieName,
  consentCookieSetOptions,
} from '../../../mcp/oauth/browser-binding';
import { renderConsentHtml } from '../../../mcp/oauth/consent-dialog';
import type { ConsentClientIdentity } from '../../../mcp/oauth/consent-dialog';
import {
  AUTH_RESTART_DESCRIPTION,
  CONSENT_HTML_HEADERS,
} from '../../../mcp/oauth/consent-html-headers';
import { isClientIdMetadataUrl } from '../../oauth/client-id-metadata-document';
import { normalizeRedirectUris } from '../../oauth/redirect-uri';
import { oauthErrorResponse } from '../oauth-error-response';

export const AUTHORIZE_CORS_HEADERS = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
  'Access-Control-Allow-Headers': 'Content-Type, Authorization',
};

/** The client fields the consent page shows. */
export const consentClientFields = (client: Client) => {
  const name: unknown = client.client_name;
  const uri: unknown = client.client_uri;

  return {
    client_name: Predicate.isString(name) ? name : undefined,
    client_uri: Predicate.isString(uri) ? uri : undefined,
    redirect_uris: normalizeRedirectUris(client.redirect_uris),
  };
};

// Registered client IDs are generated by /api/register, so only a client
// resolved from a metadata document can have an https:// ID.
export const consentClientIdentity = (
  clientId: string,
): ConsentClientIdentity =>
  isClientIdMetadataUrl(clientId)
    ? { kind: 'metadata-document', host: new URL(clientId).host }
    : { kind: 'registered' };

export const restartResponse = () =>
  oauthErrorResponse(400, 'invalid_request', AUTH_RESTART_DESCRIPTION);

type ConsentProps = Parameters<typeof renderConsentHtml>[0];

/** The consent page, setting the transaction's browser binding when given. */
export const consentResponse = (
  props: ConsentProps,
  binding?: {
    readonly transactionId: string;
    readonly browserSecret: string;
    readonly secure: boolean;
    readonly expiresAt: Date;
  },
) => {
  const page = HttpServerResponse.text(renderConsentHtml(props), {
    headers: CONSENT_HTML_HEADERS,
  });

  if (binding === undefined) {
    return page;
  }

  const options = consentCookieSetOptions(binding.secure, binding.expiresAt);

  return HttpServerResponse.setCookieUnsafe(
    page,
    consentCookieName(binding.transactionId, binding.secure),
    binding.browserSecret,
    { ...options, maxAge: Duration.seconds(options.maxAge) },
  );
};

/** The request came from an origin that is not a URL. */
export class InvalidRequestOrigin extends Schema.TaggedError<
  InvalidRequestOrigin,
  { readonly brand: unique symbol }
>()('InvalidRequestOrigin', {}) {}
